test.describe("Đính kèm tài liệu pháp lý nhà thầu", () => {
  const API = "POST /api/contractors/{id}/documents";
  test("VDR-111 Role khác upload", { tag: ["@api", "@p2"] }, async ({ http, seed, roles, leadApi, contractApi, customerApi, contractorApi, contractorContractApi }) => {
    const p = await seed.prepare(API);
    const before = await seed.snapshot(API, p);
    const res = await http.call(API, { ...p, token: roles.nvkdA.accessToken });
    expect([403]).toContain(res.status());
    expect((await body(res))?.data ?? null).toBeNull();
    expect(await seed.snapshot(API, p)).toEqual(before);
  });
  test("VDR-114 Tên file chứa đường dẫn", { tag: ["@api", "@p3"] }, async ({ http, seed, roles, leadApi, contractApi, customerApi, contractorApi, contractorContractApi }) => {
    const Q = roles.qlnt.accessToken;
    const h = await seed.contractor();
    const res = await http.call(API, { token: Q, params: { id: h.id }, multipart: { file: F.pdf(P.windowsTraversalName) } });
    expect([201, 400]).toContain(res.status());
    if (res.status() === 201) for (const d of (await seed.getContractor(h.id)).documents) expect(d.filename).not.toMatch(/\.\.[\\/]/);
  });
  test("VDR-116 Gọi không có token", { tag: ["@api", "@p2"] }, async ({ http, seed, roles, leadApi, contractApi, customerApi, contractorApi, contractorContractApi }) => {
    const p = await seed.prepare(API);
    const before = await seed.snapshot(API, p);
    const res = await http.call(API, { ...p, token: null });
    expect(res.status()).toBe(401);
    expect((await body(res))?.data ?? null).toBeNull();
    expect(await seed.snapshot(API, p)).toEqual(before);
  });
});

